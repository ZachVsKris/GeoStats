create or replace function public.record_category_validation(
  p_category_id text,
  p_status text,
  p_validation_version text,
  p_common_year integer,
  p_expected_count integer,
  p_stored_count integer,
  p_compared_count integer,
  p_value_mismatch_count integer,
  p_ranking_mismatch_count integer,
  p_source_checksum text,
  p_stored_checksum text,
  p_metadata_checks jsonb,
  p_failure_reason text,
  p_details jsonb,
  p_validation_run_id bigint default null
)
returns text
language plpgsql
security definer
set search_path=public
as $$
declare
  source_name text;
  group_name text;
begin
  if p_status not in ('verified','failed','unable_to_verify') then
    raise exception 'Invalid validation status %',p_status;
  end if;
  select source_organization,concept_group into source_name,group_name
  from public.stat_categories where id=p_category_id;
  if not found then raise exception 'Unknown stat category %',p_category_id; end if;

  insert into public.stat_category_validation_results(
    validation_run_id,category_id,source_organization,validation_status,validation_version,
    common_year,expected_observation_count,stored_observation_count,compared_observation_count,
    value_mismatch_count,ranking_mismatch_count,source_snapshot_checksum,stored_snapshot_checksum,
    metadata_checks,failure_reason,details
  ) values (
    p_validation_run_id,p_category_id,source_name,p_status,p_validation_version,
    p_common_year,p_expected_count,p_stored_count,p_compared_count,
    greatest(coalesce(p_value_mismatch_count,0),0),greatest(coalesce(p_ranking_mismatch_count,0),0),
    p_source_checksum,p_stored_checksum,coalesce(p_metadata_checks,'{}'::jsonb),p_failure_reason,coalesce(p_details,'{}'::jsonb)
  );

  update public.stat_categories set
    validation_status=p_status,
    validation_version=p_validation_version,
    validated_at=now(),
    validation_reason=case when p_status='verified' then 'Official-source values, metadata, coverage, and rankings matched the stored common-year snapshot.' else coalesce(p_failure_reason,'Source integrity validation did not pass.') end,
    source_snapshot_checksum=p_source_checksum,
    stored_snapshot_checksum=p_stored_checksum,
    validated_observation_count=p_compared_count,
    validation_expected_count=p_expected_count,
    validation_mismatch_count=greatest(coalesce(p_value_mismatch_count,0),0),
    validation_ranking_mismatch_count=greatest(coalesce(p_ranking_mismatch_count,0),0),
    enabled=case when p_status='verified' then enabled else false end,
    eligible_daily=case when p_status='verified' then eligible_daily else false end,
    auto_decision_reason=case
      when p_status='verified' then auto_decision_reason
      else 'Source integrity quarantine: '||coalesce(p_failure_reason,'validation did not pass')
    end,
    metadata=coalesce(metadata,'{}'::jsonb)||jsonb_build_object(
      'sourceIntegrityStatus',p_status,
      'sourceIntegrityVersion',p_validation_version,
      'sourceSnapshotChecksum',p_source_checksum,
      'storedSnapshotChecksum',p_stored_checksum,
      'sourceIntegrityValidatedAt',now(),
      'sourceIntegrityDetails',coalesce(p_details,'{}'::jsonb)
    ),
    updated_at=now()
  where id=p_category_id;

  perform public.apply_category_governance(p_category_id);
  return p_status;
end;
$$;

-- Duplicate arbitration is source-integrity aware. Failed and unverifiable rows
-- are always excluded. Pending rows remain available only until the one-time
-- full audit is completed and enforcement is explicitly activated.
create or replace function public.refresh_stat_concept_group(p_concept_group text)
returns text
language plpgsql
security definer
set search_path=public
as $$
declare chosen text;
declare enforce_integrity boolean:=public.source_integrity_is_enforced();
begin
  if p_concept_group is null or btrim(p_concept_group)='' then return null; end if;

  select category.id into chosen
  from public.stat_categories category
  where category.concept_group=p_concept_group
    and category.review_status<>'rejected'
    and category.auto_qualified=true
    and category.provenance_status='approved'
    and category.independent_validation=true
    and category.curation_status='approved'
    and coalesce(category.credibility_status,'quarantined')<>'quarantined'
    and coalesce(category.credibility_score,0)>=75
    and coalesce(category.objective_status,'uncertain')='objective'
    and coalesce(category.player_quality_status,'blocked')<>'blocked'
    and coalesce(category.verifiability_score,0)>=80
    and coalesce(category.understandability_score,0)>=70
    and coalesce(category.fun_score,0)>=55
    and coalesce(category.validation_status,'pending') not in ('failed','unable_to_verify')
    and (not enforce_integrity or category.validation_status='verified')
  order by
    category.governance_priority asc,
    category.validation_status='verified' desc,
    category.player_quality_status='approved' desc,
    category.verifiability_score desc,
    category.understandability_score desc,
    category.fun_score desc,
    category.credibility_score desc,
    category.quality_score desc,
    category.common_year_coverage desc,
    category.latest_available_year desc nulls last,
    category.id
  limit 1;

  update public.stat_categories category
  set
    enabled=case when category.id=chosen then true else false end,
    eligible_daily=case when category.id=chosen then true else false end,
    review_status=case
      when category.review_status='rejected' then 'rejected'
      when category.validation_status in ('failed','unable_to_verify') then 'candidate'
      when enforce_integrity and category.validation_status<>'verified' then 'needs_review'
      when category.curation_status='excluded' then 'candidate'
      when category.credibility_status='quarantined' or coalesce(category.credibility_score,0)<75 then 'candidate'
      when category.player_quality_status='blocked' then 'candidate'
      when category.id=chosen then 'approved'
      when category.auto_qualified and category.provenance_status='approved' then 'candidate'
      when category.auto_qualified then 'needs_review'
      else 'candidate'
    end,
    duplicate_status=case
      when category.validation_status in ('failed','unable_to_verify')
        or (enforce_integrity and category.validation_status<>'verified')
        or category.curation_status='excluded'
        or category.credibility_status='quarantined'
        or coalesce(category.credibility_score,0)<75
        or category.player_quality_status='blocked' then 'not_eligible'
      when category.id=chosen then 'preferred'
      when chosen is not null and category.auto_qualified and category.provenance_status='approved' then 'superseded'
      else 'not_eligible'
    end,
    superseded_by=case when category.id<>chosen and chosen is not null then chosen else null end,
    auto_decision_reason=case
      when category.validation_status in ('failed','unable_to_verify') then 'Source integrity quarantine: '||coalesce(category.validation_reason,'validation did not pass')
      when enforce_integrity and category.validation_status<>'verified' then 'Awaiting official-source integrity validation.'
      when category.curation_status='excluded' then category.curation_reason
      when category.credibility_status='quarantined' or coalesce(category.credibility_score,0)<75 then category.credibility_reason
      when category.player_quality_status='blocked' then category.player_quality_reason
      when category.id=chosen then 'Selected after source integrity, quality, provenance, credibility, objectivity, clarity, fun, and duplicate review.'
      when chosen is not null and category.auto_qualified and category.provenance_status='approved' then 'Passed the gates but was superseded by a stronger near-duplicate.'
      else category.auto_decision_reason
    end,
    updated_at=now()
  where category.concept_group=p_concept_group
    and category.review_status<>'rejected';

  return chosen;
end;
$$;

create or replace function public.apply_category_governance(p_category_id text)
returns text
language plpgsql
security definer
set search_path=public
as $$
declare group_name text;
begin
  perform public.apply_category_curation(p_category_id);
  perform public.apply_category_credibility(p_category_id);
  perform public.apply_category_player_quality(p_category_id);
  select concept_group into group_name from public.stat_categories where id=p_category_id;
  if group_name is null then
    update public.stat_categories set concept_group=id where id=p_category_id;
    group_name:=p_category_id;
  end if;
  return public.refresh_stat_concept_group(group_name);
end;
$$;

create or replace function public.activate_source_integrity_enforcement()
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare pending_enabled integer;
declare verified_count integer;
declare quarantined_count integer;
declare row record;
begin
  select count(*) into pending_enabled from public.stat_categories
  where (enabled or eligible_daily)
    and coalesce(validation_status,'pending')<>'verified';
  if pending_enabled>0 then
    raise exception 'Cannot activate source integrity enforcement: % currently playable categories are not verified.',pending_enabled;
  end if;
  update public.geostats_feature_flags
    set enabled=true,updated_at=now(),details=details||jsonb_build_object('activatedAt',now(),'activatedBy','v14.2 audit')
    where id='source_integrity_enforced';
  for row in select distinct concept_group from public.stat_categories where concept_group is not null loop
    perform public.refresh_stat_concept_group(row.concept_group);
  end loop;
  select count(*) into verified_count from public.stat_categories where validation_status='verified';
  select count(*) into quarantined_count from public.stat_categories where validation_status in ('failed','unable_to_verify');
  return jsonb_build_object('enforced',true,'verified',verified_count,'quarantined',quarantined_count);
end;
$$;

