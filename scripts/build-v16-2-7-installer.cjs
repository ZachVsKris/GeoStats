#!/usr/bin/env node
const fs = require('node:fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const migrationNames = [
  '054_v16_2_7_catalog_generator_rebuild.sql',
  '055_v16_2_7_macro_domain_product_exclusions_hotfix.sql',
  '056_v16_2_7_women_category_product_exclusion.sql',
  '057_v16_2_7_durable_editorial_enforcement.sql',
  '058_v16_2_7_legacy_reaudit_circular_block_hotfix.sql',
  '059_v16_2_7_taxonomy_and_antiproliferation_hotfix.sql',
  '060_v16_2_7_ranking_completeness_performance_hotfix.sql',
  '061_v16_2_7_bulk_source_antiproliferation.sql',
  '062_v16_2_7_vdem_curated_government.sql',
];
const migrationDir = path.join(root, 'supabase', 'migrations');
const target = path.join(root, 'RUN_THIS_IN_SUPABASE_FOR_V16_2_7.sql');
const header = [
  '-- GeoStats v16.2.7 complete one-file Supabase installer.',
  '-- GENERATED by scripts/build-v16-2-7-installer.cjs; do not hand-edit.',
  '-- Applies migrations 054-062 sequentially. Each migration remains transaction-wrapped,',
  '-- so a later hotfix failure cannot partially apply that hotfix transaction.',
  '',
].join('\n');

const body = migrationNames.map((name) => {
  const sql = fs.readFileSync(path.join(migrationDir, name), 'utf8').trimEnd();
  return `-- BEGIN ${name}\n${sql}\n-- END ${name}`;
}).join('\n\n');

const generated = `${header}${body}\n`;
if (process.argv.includes('--check')) {
  const existing = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (existing !== generated) {
    console.error('RUN_THIS_IN_SUPABASE_FOR_V16_2_7.sql is stale. Run node scripts/build-v16-2-7-installer.cjs.');
    process.exit(1);
  }
  console.log('GeoStats v16.2.7 one-file installer is synchronized with migrations 054-062.');
} else {
  fs.writeFileSync(target, generated);
  console.log(`Wrote ${path.relative(root, target)} from ${migrationNames.length} migrations.`);
}
